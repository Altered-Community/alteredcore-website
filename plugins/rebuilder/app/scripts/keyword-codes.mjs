#!/usr/bin/env node
// Single generator reading CardsData's data/csv/Keywords.csv and emitting BOTH:
//   1. plugins/rebuilder/app/src/app/core/keyword-codes.ts (fr / en)
//   2. plugins/core-altered-cards/data/keyword_codes.json (en / fr / de / es / it)
//
// Usage:
//   node scripts/keyword-codes.mjs ../../../../CardsData/data/csv/Keywords.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/keyword-codes.mjs <CardsData>/data/csv/Keywords.csv');
  process.exit(1);
}

/** RFC 4180 rows: quoted fields may hold commas, doubled quotes and line breaks. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((f) => f !== ''));
}

const [header, ...rows] = parseCsv(readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`keyword-codes: column ${name} missing in ${source}`);
  return i;
};

const refCol = col('Reference');
const localeCols = {
  en: col('DisplayWeb_en_US'),
  fr: col('DisplayWeb_fr_FR'),
  de: col('DisplayWeb_de_DE'),
  es: col('DisplayWeb_es_ES'),
  it: col('DisplayWeb_it_IT'),
};

// Inflected / token-name keyword codes referenced by card texts that are not separate rows in Keywords.csv.
const EXTRA_KEYWORD_CODES = {
  ANCHORED_FS:   { en: 'Anchored',    fr: 'Ancrée',           de: 'Verankert',   es: 'Anclaje',       it: 'Ancorato' },
  ASLEEP_CHA_P:  { en: 'Asleep',      fr: 'Endormis',         de: 'Schlafend',   es: 'Sueño',         it: 'Dormiente' },
  BLAZING_BOODA: { en: 'Blazing Booda', fr: 'Booda Brûlant',  de: 'Blazing Booda', es: 'Blazing Booda', it: 'Blazing Booda' },
  DEFENDER_TKN_P:{ en: 'Defender',    fr: 'Défenseurs',       de: 'Verteidiger', es: 'Defensores',    it: 'Difensore' },
  MOLTED_MAW:    { en: 'Molted Maw',  fr: 'Maw Métamorphosé', de: 'Molted Maw',  es: 'Molted Maw',    it: 'Molted Maw' },
  ODDBALL:       { en: 'Oddball',     fr: 'Oddball',          de: 'Oddball',     es: 'Estrambot',     it: 'Strambo' },
  TOUGH_PER_P_1: { en: 'Tough 1',     fr: 'Coriaces 1',       de: 'Robust 1',    es: 'Resistencia 1', it: 'Tenace 1' },
};

const entryMap = new Map(Object.entries(EXTRA_KEYWORD_CODES));
for (const r of rows) {
  if (!r[refCol] || (!r[localeCols.fr] && !r[localeCols.en])) continue;
  const code = r[refCol].trim();
  const enVal = (r[localeCols.en] || r[localeCols.fr]).trim();
  const frVal = (r[localeCols.fr] || enVal).trim();
  const deVal = (r[localeCols.de] || enVal).trim();
  const esVal = (r[localeCols.es] || enVal).trim();
  const itVal = (r[localeCols.it] || enVal).trim();
  entryMap.set(code, { en: enVal, fr: frVal, de: deVal, es: esVal, it: itVal });
}
const entries = [...entryMap.entries()].sort(([a], [b]) => a.localeCompare(b));

const scriptDir = dirname(fileURLToPath(import.meta.url));
const tsOut = join(scriptDir, '../src/app/core/keyword-codes.ts');
const jsonOut = join(scriptDir, '../../../core-altered-cards/data/keyword_codes.json');

const tsLines = entries.map(
  ([code, t]) => `  ${code}: { fr: ${JSON.stringify(t.fr)}, en: ${JSON.stringify(t.en)} },`,
);
writeFileSync(
  tsOut,
  `// Generated by scripts/keyword-codes.mjs from CardsData data/csv/Keywords.csv: do not edit, run the script again.\n` +
    `/** Printed name of each keyword code of the Uniques search API texts (\`[ASCENDED_P]\` → Élevées / Ascended). */\n` +
    `export const KEYWORD_CODES: Readonly<Record<string, { fr: string; en: string }>> = {\n${tsLines.join('\n')}\n};\n`,
);

const jsonObj = Object.fromEntries(entries);
writeFileSync(jsonOut, JSON.stringify(jsonObj, null, 2) + '\n');

console.log(`keyword-codes: ${entries.length} codes → ${tsOut} & ${jsonOut}`);
