#!/usr/bin/env node
// Writes src/app/core/keyword-codes.ts from CardsData's keyword table (Altered-Re-Union/CardsData,
// data/csv/Keywords.csv): the printed name, French and English, of each code the Uniques search API writes in its texts
// (`[DUE_TO_ASCENSION]`, `[ASCENDED_P]`, `[RESUPPLY_INF]`…). Run it again when CardsData adds keywords:
//
//   node scripts/keyword-codes.mjs ../../../../CardsData/data/csv/Keywords.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/keyword-codes.mjs <CardsData>/data/csv/Keywords.csv');
  process.exit(1);
}

/** RFC 4180 rows: quoted fields may hold commas, doubled quotes and line breaks. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((f) => f !== ''));
}

const [header, ...rows] = parseCsv(readFileSync(source, 'utf8').replace(/^﻿/, ''));
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`keyword-codes: column ${name} missing in ${source}`);
  return i;
};
const [ref, en, fr] = [col('Reference'), col('DisplayWeb_en_US'), col('DisplayWeb_fr_FR')];
const entries = rows
  .filter((r) => r[ref] && (r[fr] || r[en]))
  .map((r) => [r[ref].trim(), { fr: (r[fr] || r[en]).trim(), en: (r[en] || r[fr]).trim() }])
  .sort(([a], [b]) => a.localeCompare(b));

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/app/core/keyword-codes.ts');
const lines = entries.map(([code, t]) => `  ${code}: { fr: ${JSON.stringify(t.fr)}, en: ${JSON.stringify(t.en)} },`);
writeFileSync(
  out,
  `// Generated by scripts/keyword-codes.mjs from CardsData data/csv/Keywords.csv: do not edit, run the script again.\n` +
    `/** Printed name of each keyword code of the Uniques search API texts (\`[ASCENDED_P]\` → Élevées / Ascended). */\n` +
    `export const KEYWORD_CODES: Readonly<Record<string, { fr: string; en: string }>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`keyword-codes: ${entries.length} codes → ${out}`);
